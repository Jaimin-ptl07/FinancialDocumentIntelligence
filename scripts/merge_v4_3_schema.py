"""Merge the five per-statement v4.3 schema files into one loadable document.

WHY THIS EXISTS
---------------
v4.3 ships split by statement (pl / assets / liabilities / equity / cashflow),
but `fdi.pipeline.schema_store.load_schema` returns exactly ONE document, and a
document's mapping must reach every statement's concepts at once -- a balance
sheet label cannot resolve against the P&L module alone.

Worse, the file `load_schema` serves by default is the v3.2 seed, which carries
ZERO `tag` keys. `fdi.core.concepts.all_concepts` requires a tag, so wiring that
seed into the FOG made the whole of Domain 1 a SILENT no-op: 0 edges, 0 facts,
0 cost, no failure, and diagnostics identical to an honest "this report
discloses nothing". The merged document below is what the measured gate numbers
were actually produced against; before this script it existed only in memory
inside a measurement harness, which is not a configuration anything could ship.

    uv run --directory backend python ../scripts/merge_v4_3_schema.py

Writes `docs/architecture/field-extraction-schema.v4_3.json`. Point
`FDI_EXTRACTION_SCHEMA_PATH` at it, or `PUT /schema` it, to make the FOG's
mapping stage able to resolve anything at all.
"""

from __future__ import annotations

import json
import pathlib

STATEMENTS = ("pl", "assets", "liabilities", "equity", "cashflow")
ARCH = pathlib.Path(__file__).resolve().parents[1] / "docs" / "architecture"


def main() -> None:
    modules: list[object] = []
    per_file: dict[str, int] = {}
    for name in STATEMENTS:
        path = ARCH / f"field-extraction-schema.v4_3-{name}.json"
        if not path.exists():
            print(f"MISSING {path.name} -- skipped")
            continue
        doc = json.loads(path.read_text(encoding="utf-8"))
        found = doc.get("modules")
        if not isinstance(found, list):
            print(f"MALFORMED {path.name}: no `modules` list -- skipped")
            continue
        modules.extend(found)
        per_file[name] = json.dumps(found).count('"tag"')

    merged = {
        "version": "4.3.0-merged",
        "authored": (
            "GENERATED by scripts/merge_v4_3_schema.py from the five "
            "per-statement v4.3 files. Do not hand-edit; edit those and re-run."
        ),
        "reporting_unit": "as reported",
        "modules": modules,
    }
    out = ARCH / "field-extraction-schema.v4_3.json"
    out.write_text(
        json.dumps(merged, indent=1, ensure_ascii=False) + "\n", encoding="utf-8"
    )

    total = json.dumps(merged).count('"tag"')
    print(f"wrote {out.name}: {len(modules)} modules, {total} tag keys")
    for name, count in per_file.items():
        print(f"  {name:12s} {count:>4} tags")
    if total == 0:
        raise SystemExit(
            "REFUSING a schema with no tags: it would make the FOG a silent no-op"
        )


if __name__ == "__main__":
    main()
